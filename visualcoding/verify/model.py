# ----------------------------------------------------------------------------- images
def load_task_images(paths, max_pixels: int, min_pixels: int):
    """Mirror the agent harness parse_and_load_multiple_images: originals via fetch_image (smart_resize to the
    pixel budget), API parts as base64 JPEG data URIs."""
    image_map: dict[str, Image.Image] = {}
    image_list: list[tuple[str, Image.Image]] = []
    parts: list[dict] = []
    for i, p in enumerate(paths):
        name = f"original_image_{i}" if i > 0 else "original_image"
        img = fetch_image({"image": str(p), "max_pixels": max_pixels})
        image_map[name] = img
        image_list.append((name, img))
        parts.append({"type": "image_url", "image_url": {"url": pil_to_base64_data_uri(img)}})
    return image_map, image_list, parts


def image_part(img: Image.Image, max_pixels: int, min_pixels: int) -> tuple[dict, tuple[int, int]]:
    """Resize like the agent harness's tool handler does before sending; returns (content part, sent (w, h))."""
    processed = process_image(img, max_pixels, min_pixels)
    return ({"type": "image_url", "image_url": {"url": pil_to_base64_data_uri(processed)}},
            (processed.width, processed.height))


# ----------------------------------------------------------------------------- calls
USAGE: dict = {}                     # model -> {n, in_tokens, out_tokens, think_tokens}: cumulative over this process (cost accounting only)
_USAGE_LOCK = __import__("threading").Lock()


def call_model(messages: list[dict], model_name: str, sampling: dict, tools: list | None):
    """Returns the agent harness's response dict ({content, tool_calls?, gemini_parts}) or an 'Error: ...' string / None."""
    resp = call_vision_api(model_name, messages, sampling, tools=tools)
    u = resp.get("usage") if isinstance(resp, dict) else None
    with _USAGE_LOCK:
        d = USAGE.setdefault(model_name, {"n": 0, "in_tokens": 0, "out_tokens": 0, "think_tokens": 0, "cache_hit_tokens": 0})
        d["n"] += 1
        if isinstance(u, dict):
            for k, kk in (("input_tokens", "in_tokens"), ("output_tokens", "out_tokens"), ("thinking_tokens", "think_tokens"), ("cache_hit_tokens", "cache_hit_tokens")):
                d[kk] += int(u.get(k) or 0)      # cache_hit_tokens: part of in_tokens served from the prefix cache (OpenAI-style endpoints that report it)
    return resp


def tool_feedback(tool_call_id: str, result_text: str, new_images: list[tuple[str, Image.Image]],
                  max_pixels: int, min_pixels: int, usage_text: str = ""):
    """Build the tool-role message (+ a user message carrying the images), mirroring the agent harness's
    APIToolHandler.execute_tool_call. Returns (api_messages, text_summary, sent_sizes)."""
    sent: dict[str, tuple[int, int]] = {}
    if new_images:
        refs = " ".join(f"![{n}]({n}.png)" for n, _ in new_images)
        processed = f"{result_text}\n\n{refs}".strip()
    else:
        processed = result_text
    msgs = [{"role": "tool", "content": json.dumps({"result": processed}), "tool_call_id": tool_call_id or "call_0"}]
    if new_images:
        content = []
        for n, img in new_images:
            part, wh = image_part(img, max_pixels, min_pixels)
            sent[n] = wh
            content.append(part)
        content.append({"type": "text", "text": f"Images from tool output: {processed}{usage_text}"})
        msgs.append({"role": "user", "content": content})
        summary = f"Tool 'code_interpreter' returned with images: {processed}{usage_text}"
    else:
        summary = f"Tool 'code_interpreter' returned: {result_text}{usage_text}"
    return msgs, summary, sent


def last_answer(text: str | None) -> str | None:
    """Last <answer>...</answer> in `text` (judge parity: the extractor takes the last match)."""
    if not text:
        return None
    m = _ANSWER_RE.findall(text)
    return m[-1].strip() if m else None


def approx_tokens(messages: list[dict], per_image: int = 1000) -> int:
    n = 0
    for m in messages:
        c = m.get("content")
        if isinstance(c, str):
            n += estimate_tokens(c)
        elif isinstance(c, list):
            for part in c:
                if part.get("type") == "text":
                    n += estimate_tokens(part.get("text", ""))
                elif part.get("type") == "image_url":
                    n += per_image
        for tc in m.get("tool_calls") or []:
            n += estimate_tokens(json.dumps(tc.get("function", {})))
    return n
